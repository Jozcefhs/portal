// Synthetic, offline preview only. Does not read patient records or send email.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { PNG } from 'pngjs';
import { createClinicReferralPdf } from '../functions/lib/clinic-referral-pdf.js';

const output = new URL('../output/pdf/clinic-hospital-referral-sample.pdf', import.meta.url);
const logo = await readFile(new URL('../images/Logo.png', import.meta.url));
// Fictional pen strokes for layout QA, never an actual staff signature.
const signature = new PNG({ width: 360, height: 100 });
signature.data.fill(0);
const strokes = [
  [[12, 74], [32, 20], [46, 48], [36, 78], [22, 58], [60, 30], [48, 78]],
  [[58, 69], [76, 38], [90, 70], [104, 40], [118, 66], [139, 34], [135, 77], [157, 51], [180, 64]],
  [[170, 68], [198, 24], [185, 77], [208, 49], [229, 68], [247, 42], [263, 64], [295, 47], [310, 60]],
  [[30, 88], [316, 77]]
];
for (const stroke of strokes) for (let i = 1; i < stroke.length; i++) {
  const [x0, y0] = stroke[i - 1], [x1, y1] = stroke[i];
  const steps = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0));
  for (let step = 0; step <= steps; step++) for (let dx = -1; dx <= 1; dx++) for (let dy = -1; dy <= 1; dy++) {
    const x = Math.round(x0 + (x1 - x0) * step / steps) + dx, y = Math.round(y0 + (y1 - y0) * step / steps) + dy;
    if (x >= 0 && y >= 0 && x < signature.width && y < signature.height) {
      const index = (y * signature.width + x) * 4;
      signature.data[index] = 25; signature.data[index + 1] = 35; signature.data[index + 2] = 55; signature.data[index + 3] = 255;
    }
  }
}
const pdf = await createClinicReferralPdf({ SchoolName: 'EXAMPLE SCHOOL - SAMPLE ONLY', SchoolAddress: 'School clinic - sample address',
  DocumentLogoDataUrl: `data:image/png;base64,${logo.toString('base64')}` }, {
  ReferralId: 'REF-SAMPLE-NOT-FOR-CLINICAL-USE', ReferralDate: '2026-10-16', StudentName: 'Sample Learner',
  AccountRef: 'SAMPLE/001', ClassName: 'Grade 10 / Sample Arm', VisitDate: '2026-10-16', Hospital: 'Example Hospital',
  Reason: 'This is a demonstration of the hospital referral template. The clinic officer enters the actual reason for further assessment here.',
  Observations: 'The clinic officer records relevant observations here. No diagnosis is generated by the system.',
  Treatment: 'The clinic officer records any care already provided, with relevant times and details.',
  Instructions: 'The clinic officer enters the arrangements and follow-up instructions for the parent here.',
  PreparedBy: 'Sample Clinic Officer', ClinicianTitle: 'Clinic officer', ClinicContact: 'clinic@example.org'
}, { signatureDataUrl: `data:image/png;base64,${PNG.sync.write(signature).toString('base64')}` });
await mkdir(new URL('.', output), { recursive: true });
await writeFile(output, pdf);
console.log(output.pathname);
